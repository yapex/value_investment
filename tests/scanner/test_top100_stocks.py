def test_top100_gross_margin_filter():
    """从 100 家知名 A 股公司中筛选毛利率>30% 的股票"""
    scanner = Scanner(market="A")
    
    print(f"\n测试股票数量：{len(TOP_100_A_SHARES)} 只")
    
    # 获取财务数据（毛利率）
    print("获取财务数据（毛利率）...")
    financials = scanner.get_financial_data(
        stocks=TOP_100_A_SHARES,
        fields=['gross_profit_margin'],
        years=3
    )
    
    print(f"获取到 {financials['stock_code'].nunique()} 只股票的数据")
    
    # 筛选：最近一年毛利率 > 30%
    result = filters.latest_year(financials, field='gross_profit_margin', min_value=30)
    
    print(f"\n毛利率 > 30% 的股票：{result['stock_code'].nunique()} 只")
    
    if not result.empty:
        # 获取股票名称
        stocks = scanner.get_stock_list()
        result_named = result.merge(
            stocks[['symbol', 'name']],
            left_on='stock_code',
            right_on='symbol'
        )
        
        print("\n符合条件的股票:")
        for code in result_named['stock_code'].unique():
            name = result_named[result_named['stock_code'] == code]['name'].iloc[0]
            margins = result_named[result_named['stock_code'] == code]['gross_profit_margin'].tolist()
            print(f"  - {code} ({name}): 毛利率 = {margins}%")
    
    assert not result.empty, "应该至少有一只股票毛利率>30%"


